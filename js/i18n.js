window.i18nManager = {
  lang: 'fr',

  init() {
    this.lang = localStorage.getItem('lang') || 'fr';
    this.apply(this.lang);
    this.bindLangSwitch();
  },

  t(key) {
    const keys = key.split('.');
    let val = window.I18N[this.lang];
    for (const k of keys) {
      if (!val || val[k] === undefined) return key;
      val = val[k];
    }
    return val;
  },

  apply(lang) {
    if (!window.I18N[lang]) return;
    this.lang = lang;
    localStorage.setItem('lang', lang);

    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

    const meta = window.I18N[lang].meta;
    document.title = meta.title;
    const desc = document.querySelector('meta[name="description"]');
    if (desc) desc.content = meta.description;

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.dataset.i18n;
      const val = this.t(key);
      if (typeof val === 'string') el.textContent = val;
    });

    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const val = this.t(el.dataset.i18nHtml);
      if (typeof val === 'string') el.innerHTML = val;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.placeholder = this.t(el.dataset.i18nPlaceholder);
    });

    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      el.setAttribute('aria-label', this.t(el.dataset.i18nAria));
    });

    document.querySelectorAll('.lang-switch__btn').forEach((btn) => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
      btn.setAttribute('aria-pressed', btn.dataset.lang === lang);
    });

    window.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  },

  bindLangSwitch() {
    document.querySelectorAll('.lang-switch__btn').forEach((btn) => {
      btn.addEventListener('click', () => this.apply(btn.dataset.lang));
    });
  },

  getTypewriterRoles() {
    return window.I18N[this.lang].hero.typewriter;
  }
};
